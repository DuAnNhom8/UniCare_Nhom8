/** Kiểm thử 3 task mở rộng – Node >=22, không cần npm hay Backend */
import assert from 'node:assert/strict';
import {existsSync,readFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const dir=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const storage=new Map();
globalThis.localStorage={getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,String(v)),removeItem:k=>storage.delete(k)};
const {api,portalApi,APP_CONFIG}=await import('../assets/js/api.js');
assert.equal(APP_CONFIG.MODE,'mock');
const dash=await portalApi.adminDashboard();
assert.ok(dash.total_users>=5);
assert.ok(dash.pending_jobs>=3);
assert.ok((await portalApi.listModerationJobs()).some(j=>j.job_id===115&&j.approval_status==='PENDING'));
const users=await portalApi.listUsers();
const u=users.find(u=>u.user_id===3);
assert.ok(u?.is_active);
await portalApi.setUserActive(3,false);
assert.equal((await portalApi.listUsers()).find(u=>u.user_id===3).is_active,false);
await portalApi.setUserActive(3,true);
assert.equal((await portalApi.listUsers()).find(u=>u.user_id===3).is_active,true);
await assert.rejects(()=>portalApi.setUserActive(99,false),error=>error.status===403);
const jobsBefore=await api.listJobs({pageSize:100});
assert.ok(!jobsBefore.items.some(j=>j.job_id===115));
await portalApi.moderateJob(115,'APPROVED');
assert.ok((await api.listJobs({pageSize:100})).items.some(j=>j.job_id===115),'Tin mới duyệt hiện ở Candidate');
await assert.rejects(()=>portalApi.moderateJob(115,'REJECTED'),err=>err.status===409);
await portalApi.hideJob(115);
assert.ok(!(await api.listJobs({pageSize:100})).items.some(j=>j.job_id===115),'Ẩn tin xóa khỏi tìm kiếm');
await portalApi.moderateJob(116,'REJECTED');
assert.equal((await portalApi.listModerationJobs()).find(j=>j.job_id===116).approval_status,'REJECTED');
const employerJobs=await portalApi.listEmployerJobs();
assert.ok(employerJobs.some(j=>j.job_id===101));
assert.ok(!employerJobs.some(j=>j.job_id===102),'Không lộ tin công ty khác');
const apps=await portalApi.listEmployerApplications();
assert.ok(apps.length>=3);
assert.ok(apps.every(a=>a.job_id===101),'Chỉ lấy đơn ứng tuyển vào tin công ty');
const initial=apps.find(a=>a.application_id===801);
assert.equal(initial.candidate_name,'Lê Bảo Ngọc');
await portalApi.changeApplicationStatus(801,'REVIEWING');
assert.equal((await portalApi.listEmployerApplications()).find(a=>a.application_id===801).status,'REVIEWING');
await assert.rejects(()=>portalApi.changeApplicationStatus(804,'ACCEPTED'),err=>err.status===403);
const newApp=await api.submitApplication({jobId:101,coverLetter:'Em ứng tuyển thực tập.'});
const latest=await portalApi.listEmployerApplications();
assert.ok(latest.some(a=>a.application_id===newApp.application_id&&a.candidate_id===1),'Candidate submit -> Employer list');
await portalApi.changeApplicationStatus(newApp.application_id,'ACCEPTED');
assert.equal((await api.listApplications()).find(a=>a.application_id===newApp.application_id).status,'ACCEPTED','Employer update -> Candidate view');
const analysis=await portalApi.analyzeCV({candidateId:3,jobId:101});
assert.equal(analysis.engine,'demo_keyword');
assert.ok(analysis.ai_match_score>=0&&analysis.ai_match_score<=100);
assert.ok(Array.isArray(analysis.matched_skills));
await assert.rejects(()=>portalApi.analyzeCV({candidateId:3,jobId:114}),err=>err.status===400,'Không phân tích tin đã đóng');
const candidateAnalysis=await portalApi.analyzeCV({jobId:101,cvText:'Python FastAPI MySQL Git'});
assert.ok(candidateAnalysis.ai_match_score>0,'Ứng viên đánh giá CV của mình');
await assert.rejects(()=>portalApi.analyzeCV({jobId:101,cvText:'hi'}),err=>err.status===400);
const pages=['pages/admin/dashboard.html','pages/admin/users.html','pages/admin/approve-jobs.html','pages/company/applications.html','pages/company/ai-recommend.html','pages/candidate/ai-matching.html'];
for(const p of pages){assert.ok(existsSync(path.join(dir,p)),p);const html=readFileSync(path.join(dir,p),'utf8');assert.match(html,/<html lang="vi">/);assert.match(html,/assets\/js\/\w+(-\w+)?\.js/);}
for(const f of ['assets/css/admin.css','assets/css/company.css','assets/js/admin.js','assets/js/company.js','assets/js/ai-matching.js','assets/js/portal-ui.js'])assert.ok(existsSync(path.join(dir,f)),f);
console.log('✓ PASS: Admin role/tài khoản/duyệt tin, Employer hồ sơ & trạng thái, AI demo, chia sẻ dữ liệu Candidate↔Employer, file HTML/CSS/JS.');
